-- Cria um pedido conferindo preços, tamanhos e endereço no próprio banco.
-- p_itens: [{"id": 18, "tamanho": 37, "qtd": 1}, ...]
create or replace function public.criar_pedido(p_itens jsonb, p_forma text, p_validade_min int default 5)
returns public.pedidos
language plpgsql security definer set search_path = public as $$
declare
  v_perfil   public.perfis;
  v_item     jsonb;
  v_prod     public.produtos;
  v_qtd      int;
  v_tam      int;
  v_itens    jsonb := '[]'::jsonb;
  v_subtotal numeric(10,2) := 0;
  v_total    numeric(10,2);
  v_end      jsonb;
  v_pedido   public.pedidos;
  -- Desconto do Pix: precisa ser igual ao "desconto" do arquivo js/pix.js
  c_desconto_pix constant numeric := 0.05;
begin
  if auth.uid() is null then raise exception 'Entre na sua conta para comprar.'; end if;
  select * into v_perfil from public.perfis where id = auth.uid();
  if not found then raise exception 'Perfil não encontrado.'; end if;
  v_end := v_perfil.endereco;
  if coalesce(v_end->>'rua', '') = '' then raise exception 'Cadastre um endereço de entrega.'; end if;
  if p_forma <> 'pix' then raise exception 'Forma de pagamento indisponível.'; end if;
  if jsonb_typeof(p_itens) <> 'array' or jsonb_array_length(p_itens) = 0 or jsonb_array_length(p_itens) > 30 then
    raise exception 'Carrinho vazio ou inválido.';
  end if;

  for v_item in select * from jsonb_array_elements(p_itens) loop
    select * into v_prod from public.produtos where id = (v_item->>'id')::bigint and ativo;
    if not found then raise exception 'Um produto do carrinho não está mais disponível.'; end if;
    v_qtd := (v_item->>'qtd')::int;
    v_tam := (v_item->>'tamanho')::int;
    if v_qtd is null or v_qtd < 1 or v_qtd > 20 then raise exception 'Quantidade inválida.'; end if;
    if coalesce(cardinality(v_prod.tamanhos), 0) > 0 then
      if not (v_tam = any(v_prod.tamanhos)) then raise exception 'Tamanho % indisponível para %.', v_tam, v_prod.nome; end if;
    elsif v_tam is null or v_tam < 34 or v_tam > (case when v_prod.genero = 'feminino' then 39 else 43 end) then
      raise exception 'Tamanho % indisponível para %.', v_tam, v_prod.nome;
    end if;
    v_subtotal := v_subtotal + v_prod.preco * v_qtd;
    v_itens := v_itens || jsonb_build_object('id', v_prod.id, 'nome', v_prod.nome, 'preco', v_prod.preco, 'qtd', v_qtd, 'tamanho', v_tam);
  end loop;

  v_total := round(round(v_subtotal * 100) * (1 - c_desconto_pix)) / 100;

  insert into public.pedidos (cliente, cliente_nome, cliente_email, itens, subtotal, desconto, total, forma, pagamento, endereco, expira_em)
  values (auth.uid(), v_perfil.nome, v_perfil.email, v_itens, v_subtotal, v_subtotal - v_total, v_total, 'pix', 'Pix',
          concat(v_end->>'rua', ', ', v_end->>'numero',
                 case when coalesce(v_end->>'complemento', '') <> '' then ' - ' || (v_end->>'complemento') else '' end,
                 ' · ', v_end->>'bairro', ', ', v_end->>'cidade', '/', v_end->>'estado', ' · CEP ', v_end->>'cep'),
          now() + make_interval(mins => greatest(1, least(coalesce(p_validade_min, 5), 60))))
  returning * into v_pedido;
  return v_pedido;
end $$;
revoke all on function public.criar_pedido(jsonb, text, int) from public, anon;
grant execute on function public.criar_pedido(jsonb, text, int) to authenticated;

-- Cliente "exclui" um Pix vencido e não pago: o pedido some da lista dele,
-- mas continua visível para o administrador como "Cancelado pelo cliente".
create or replace function public.cancelar_pedido_expirado(p_numero text) returns void
language plpgsql security definer set search_path = public as $$
begin
  update public.pedidos set status = 'Cancelado pelo cliente', atualizado_em = now()
   where numero = p_numero and cliente = auth.uid()
     and status = 'Aguardando pagamento' and expira_em < now();
  if not found then raise exception 'Este pedido não pode ser excluído.'; end if;
end $$;
revoke all on function public.cancelar_pedido_expirado(text) from public, anon;
grant execute on function public.cancelar_pedido_expirado(text) to authenticated;

-- Administrador muda o status de um pedido (ex.: confirmou o Pix, enviou).
create or replace function public.mudar_status_pedido(p_numero text, p_status text) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.eh_admin() then raise exception 'Acesso negado.'; end if;
  update public.pedidos set status = p_status, atualizado_em = now() where numero = p_numero;
  if not found then raise exception 'Pedido não encontrado.'; end if;
end $$;
revoke all on function public.mudar_status_pedido(text, text) from public, anon;
grant execute on function public.mudar_status_pedido(text, text) to authenticated;

-- Administrador adiciona ou remove outro administrador pelo e-mail.
-- A pessoa precisa ter criado a conta no site antes.
create or replace function public.definir_admin(p_email text, p_admin boolean) returns void
language plpgsql security definer set search_path = public as $$
begin
  if not public.eh_admin() then raise exception 'Acesso negado.'; end if;
  if not p_admin and (select count(*) from public.perfis where papel = 'admin') <= 1
     and exists (select 1 from public.perfis where email = lower(trim(p_email)) and papel = 'admin') then
    raise exception 'A loja precisa ter pelo menos um administrador.';
  end if;
  update public.perfis set papel = case when p_admin then 'admin' else 'cliente' end
   where email = lower(trim(p_email));
  if not found then raise exception 'Nenhuma conta com este e-mail. A pessoa precisa se cadastrar no site primeiro.'; end if;
end $$;
revoke all on function public.definir_admin(text, boolean) from public, anon;
grant execute on function public.definir_admin(text, boolean) to authenticated;

-- Resumo do fluxo do site para o painel (só administradores).
create or replace function public.resumo_fluxo(p_dias int default 30) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare
  v_desde timestamptz := date_trunc('day', now() at time zone 'America/Sao_Paulo') at time zone 'America/Sao_Paulo'
                         - make_interval(days => greatest(1, least(p_dias, 365)) - 1);
  v jsonb;
begin
  if not public.eh_admin() then raise exception 'Acesso negado.'; end if;
  with ev as (select * from public.eventos where criado_em >= v_desde),
       dias as (select generate_series((v_desde at time zone 'America/Sao_Paulo')::date,
                                       (now() at time zone 'America/Sao_Paulo')::date, '1 day')::date as dia),
       ped as (select * from public.pedidos where criado_em >= v_desde)
  select jsonb_build_object(
    'por_dia', (select coalesce(jsonb_agg(jsonb_build_object('dia', d.dia,
                  'visitas', (select count(*) from ev where tipo = 'visita' and (criado_em at time zone 'America/Sao_Paulo')::date = d.dia),
                  'visitantes', (select count(distinct sessao) from ev where (criado_em at time zone 'America/Sao_Paulo')::date = d.dia),
                  'pedidos', (select count(*) from ped where (criado_em at time zone 'America/Sao_Paulo')::date = d.dia)
                ) order by d.dia), '[]'::jsonb) from dias d),
    'funil', jsonb_build_object(
       'visitantes',   (select count(distinct sessao) from ev),
       'viram_produto',(select count(distinct sessao) from ev where tipo = 'ver_produto'),
       'add_carrinho', (select count(distinct sessao) from ev where tipo = 'add_carrinho'),
       'checkout',     (select count(distinct sessao) from ev where tipo = 'checkout'),
       'pedido',       (select count(distinct sessao) from ev where tipo = 'pedido')),
    'produtos', (select coalesce(jsonb_agg(x order by x.vistas desc, x.adicoes desc), '[]'::jsonb) from (
                   select e.produto_id as id, coalesce(p.nome, 'Produto removido') as nome,
                          count(*) filter (where e.tipo = 'ver_produto') as vistas,
                          count(*) filter (where e.tipo = 'add_carrinho') as adicoes
                     from ev e left join public.produtos p on p.id = e.produto_id
                    where e.produto_id is not null group by e.produto_id, p.nome
                    order by 3 desc, 4 desc limit 10) x),
    'paginas', (select coalesce(jsonb_agg(x order by x.visitas desc), '[]'::jsonb) from (
                   select pagina, count(*) as visitas from ev where tipo = 'visita'
                    group by pagina order by 2 desc limit 10) x),
    'pedidos', jsonb_build_object(
       'total',        (select count(*) from ped where status not like 'Cancelado%'),
       'aguardando',   (select count(*) from public.pedidos where status = 'Aguardando pagamento' and expira_em >= now()),
       'pagos',        (select count(*) from ped where status in ('Pagamento aprovado', 'Enviado', 'Entregue')),
       'faturamento',  (select coalesce(sum(total), 0) from ped where status in ('Pagamento aprovado', 'Enviado', 'Entregue')),
       'para_enviar',  (select count(*) from public.pedidos where status = 'Pagamento aprovado')),
    'clientes_novos', (select count(*) from public.perfis where criado_em >= v_desde)
  ) into v;
  return v;
end $$;
revoke all on function public.resumo_fluxo(int) from public, anon;
grant execute on function public.resumo_fluxo(int) to authenticated;

-- Atualiza a data de alteração dos produtos
create or replace function public.tocar_atualizado() returns trigger language plpgsql as $$
begin new.atualizado_em := now(); return new; end $$;
drop trigger if exists produtos_atualizado on public.produtos;
create trigger produtos_atualizado before update on public.produtos
  for each row execute function public.tocar_atualizado();

