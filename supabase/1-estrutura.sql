-- ---------- Perfis (dados de cada cliente e quem é administrador) ----------
create table if not exists public.perfis (
  id          uuid primary key references auth.users(id) on delete cascade,
  email       text not null,
  nome        text not null default '',
  cpf         text not null default '',
  telefone    text not null default '',
  nascimento  date,
  endereco    jsonb not null default '{}'::jsonb,
  papel       text not null default 'cliente' check (papel in ('cliente', 'admin')),
  criado_em   timestamptz not null default now()
);

-- Cria o perfil automaticamente quando alguém se cadastra no site
create or replace function public.novo_usuario() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.perfis (id, email, nome)
  values (new.id, lower(new.email), coalesce(new.raw_user_meta_data->>'nome', ''))
  on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists ao_criar_usuario on auth.users;
create trigger ao_criar_usuario after insert on auth.users
  for each row execute function public.novo_usuario();

-- Quem está logado é administrador?
create or replace function public.eh_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from public.perfis where id = auth.uid() and papel = 'admin');
$$;

-- ---------- Produtos ----------
create table if not exists public.produtos (
  id            bigint generated by default as identity primary key,
  nome          text not null,
  genero        text not null check (genero in ('feminino', 'masculino')),
  tipo          text not null check (tipo in ('tenis', 'chinelo')),
  preco         numeric(10,2) not null check (preco > 0),
  preco_antigo  numeric(10,2) check (preco_antigo is null or preco_antigo > preco),
  destaque      boolean not null default false,
  lancamento    boolean not null default false,
  ativo         boolean not null default true,      -- false = escondido da loja
  descricao     text not null default '',
  cor           text not null default '#111111',    -- cores do desenho (quando não há foto)
  sola          text not null default '#ffffff',
  imagens       jsonb not null default '[]'::jsonb, -- [{src, alt, foco}]
  tamanhos      int[],                              -- vazio = padrão (fem. 34–39, masc. 34–43)
  ordem         int not null default 0,             -- menor aparece primeiro
  atualizado_em timestamptz not null default now()
);

-- ---------- Pedidos ----------
create sequence if not exists public.pedido_numero_seq start 1001;
create table if not exists public.pedidos (
  id         bigint generated always as identity primary key,
  numero     text not null unique default lpad(nextval('public.pedido_numero_seq')::text, 6, '0'),
  cliente    uuid references public.perfis(id) on delete set null,
  cliente_nome  text not null default '',
  cliente_email text not null default '',
  itens      jsonb not null,           -- [{id, nome, preco, qtd, tamanho}]
  subtotal   numeric(10,2) not null,
  desconto   numeric(10,2) not null default 0,
  total      numeric(10,2) not null,
  forma      text not null,            -- pix
  pagamento  text not null,            -- texto mostrado ao cliente
  endereco   text not null default '',
  status     text not null default 'Aguardando pagamento'
             check (status in ('Aguardando pagamento', 'Pagamento aprovado', 'Enviado', 'Entregue', 'Cancelado', 'Cancelado pelo cliente')),
  expira_em  timestamptz,
  criado_em  timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create index if not exists pedidos_cliente_idx on public.pedidos (cliente, criado_em desc);
create index if not exists pedidos_criado_idx on public.pedidos (criado_em desc);

-- ---------- Fluxo do site (visitas, produtos vistos, carrinho...) ----------
create table if not exists public.eventos (
  id         bigint generated always as identity primary key,
  criado_em  timestamptz not null default now(),
  sessao     text not null,   -- código aleatório do navegador (sem dados pessoais)
  tipo       text not null check (tipo in ('visita', 'ver_produto', 'add_carrinho', 'checkout', 'pedido')),
  pagina     text not null default '',
  produto_id bigint,
  check (char_length(sessao) between 8 and 40 and char_length(pagina) <= 120)
);
create index if not exists eventos_criado_idx on public.eventos (criado_em desc);

-- ---------- Newsletter (e-mails do "Ganhe 10% OFF") ----------
create table if not exists public.newsletter (
  email     text primary key check (email ~* '^[^@\s]+@[^@\s]+\.[^@\s]+$' and char_length(email) <= 200),
  criado_em timestamptz not null default now()
);

