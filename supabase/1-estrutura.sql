-- Perfis: cada cliente vê e edita só o próprio; administradores veem todos.
-- O cliente NÃO consegue mudar o próprio "papel" nem o e-mail.
drop policy if exists perfis_ver on public.perfis;
create policy perfis_ver on public.perfis for select using (id = auth.uid() or public.eh_admin());
drop policy if exists perfis_editar on public.perfis;
create policy perfis_editar on public.perfis for update using (id = auth.uid()) with check (id = auth.uid());
revoke insert, update, delete on public.perfis from anon, authenticated;
grant select on public.perfis to authenticated;
grant update (nome, cpf, telefone, nascimento, endereco) on public.perfis to authenticated;

-- Produtos: todos veem os ativos; só administradores criam, editam e apagam.
drop policy if exists produtos_ver on public.produtos;
create policy produtos_ver on public.produtos for select using (ativo or public.eh_admin());
drop policy if exists produtos_admin on public.produtos;
create policy produtos_admin on public.produtos for all using (public.eh_admin()) with check (public.eh_admin());
grant select on public.produtos to anon, authenticated;
grant insert, update, delete on public.produtos to authenticated;

-- Pedidos: o cliente vê os seus; o administrador vê todos.
-- Ninguém grava direto na tabela: pedidos são criados pela função criar_pedido,
-- que confere os preços no banco (o cliente não consegue mudar o valor).
drop policy if exists pedidos_ver on public.pedidos;
create policy pedidos_ver on public.pedidos for select using (cliente = auth.uid() or public.eh_admin());
revoke insert, update, delete on public.pedidos from anon, authenticated;
grant select on public.pedidos to authenticated;

-- Eventos e newsletter: qualquer visitante pode registrar; só administradores leem.
drop policy if exists eventos_registrar on public.eventos;
create policy eventos_registrar on public.eventos for insert with check (true);
drop policy if exists eventos_ver on public.eventos;
create policy eventos_ver on public.eventos for select using (public.eh_admin());
revoke update, delete on public.eventos from anon, authenticated;
grant insert on public.eventos to anon, authenticated;
grant select on public.eventos to authenticated;

drop policy if exists newsletter_registrar on public.newsletter;
create policy newsletter_registrar on public.newsletter for insert with check (true);
drop policy if exists newsletter_ver on public.newsletter;
create policy newsletter_ver on public.newsletter for select using (public.eh_admin());
revoke update, delete on public.newsletter from anon, authenticated;
grant insert on public.newsletter to anon, authenticated;
grant select on public.newsletter to authenticated;

